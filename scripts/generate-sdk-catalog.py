#!/usr/bin/env python3
"""Regenerate the complete API inventory from the resolved Vehicle AAR, never a hand-maintained subset.
Run ./gradlew :app:assembleDebug first, then python3 scripts/generate-sdk-catalog.py.
Requires JDK 21 and the Gradle dependency cache. No vehicle service is used.
"""
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
CACHE = Path(os.environ.get('GRADLE_USER_HOME', str(Path.home() / '.gradle'))) / 'caches/modules-2/files-2.1'

def artifact(group, name, version, suffix):
    return next((CACHE / group / name / version).rglob('*.' + suffix))

with tempfile.TemporaryDirectory() as tmp:
    work = Path(tmp)
    aar = artifact('ai.pleos.playground', 'Vehicle', '2.3.2', 'aar')
    jar = work / 'vehicle.jar'
    with zipfile.ZipFile(aar) as z:
        jar.write_bytes(z.read('classes.jar'))
    with zipfile.ZipFile(jar) as z:
        domains = sorted(n[:-6].replace('/', '.') for n in z.namelist()
                         if re.fullmatch(r'ai/pleos/playground/vehicle/api/\w+\.class', n))
    metadata, inventory, permissions = {}, {}, set()
    for cls in domains:
        verbose = subprocess.check_output(['javap', '-v', '-classpath', str(jar), cls], text=True)
        chunks = re.split(r'(?=^  public (?:abstract|default) void )', verbose, flags=re.M)
        inventory[cls.rsplit('.', 1)[1]] = []
        for chunk in chunks[1:]:
            header = chunk.splitlines()[0]
            name = re.search(r'void (\w+)\(', header)[1]
            desc = re.search(r'descriptor: (\S+)', chunk)[1]
            declared = re.findall(r'value="(pleos.car.permission.[A-Z_]+)"', chunk)
            permissions.update(declared)
            key = cls + '#' + name + desc
            metadata[key] = {'permission': declared[0] if declared else '',
                             'deprecated': 'Deprecated: true' in chunk}
            inventory[cls.rsplit('.', 1)[1]].append((key, header.strip()))
    # Kotlin names (area, position, value, onComplete, onFailed, ...).
    support = [jar]
    for package in ('vehicle-data', 'vehicle-aidl'):
        folder = CACHE / 'ai.pleos.playground' / package
        for dependency in folder.rglob('*.aar'):
            output = work / (package + '.jar')
            with zipfile.ZipFile(dependency) as z:
                output.write_bytes(z.read('classes.jar'))
            support.append(output)
    for package in ('kotlin-stdlib', 'kotlin-reflect'):
        support.append(artifact('org.jetbrains.kotlin', package, '2.2.10', 'jar'))
    classpath = os.pathsep.join(map(str, support))
    subprocess.run(['javac', '-cp', classpath, '-d', tmp, str(ROOT / 'scripts/ExportParameterNames.java')], check=True)
    names = subprocess.check_output(['java', '-cp', tmp + os.pathsep + classpath,
                                     'ExportParameterNames', *domains], text=True)
    for line in names.splitlines():
        key, values = line.split('\t')
        if key in metadata:
            metadata[key]['parameters'] = values.split(',') if values else []
    assets = ROOT / 'app/src/main/assets'
    assets.mkdir(parents=True, exist_ok=True)
    (assets / 'api-metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')
    docs = ROOT / 'docs'
    docs.mkdir(exist_ok=True)
    lines = ['# Vehicle SDK 2.3.2 API inventory', '',
             f'{len(domains)} domains · {len(metadata)} public API signatures (including deprecated overloads).', '',
             'Generated by `python3 scripts/generate-sdk-catalog.py` from the resolved AAR.', '']
    for domain, methods in inventory.items():
        lines += [f'## {domain} ({len(methods)})', '']
        for key, declaration in methods:
            item = metadata[key]
            args = ', '.join(item.get('parameters', []))
            method_name = key.split('#')[1].split('(')[0]
            legacy = ' [deprecated]' if item['deprecated'] else ''
            lines.append(f'- `{method_name}({args})`{legacy} — `{item["permission"]}`')
        lines.append('')
    (docs / 'vehicle-sdk-api-inventory.md').write_text('\n'.join(lines))
    (assets / 'sdk-permissions.json').write_text(json.dumps(sorted(permissions), indent=2) + '\n')
    print(f'{len(domains)} domains, {len(metadata)} signatures, {len(permissions)} permissions')
